/**
 * Per-country phone formats: an example national number, for the placeholder, the national
 * number lengths the country allows and its trunk prefix, for validation. The example's own
 * length is always among the lengths, because a few countries format mobile numbers with an
 * extra national token (Argentina's "15"). Like dial-codes.ts this is generated data, and only
 * data that cannot be derived. Regenerate from ../cars-secrets-api with:
 *
 *   uv run python -c "
 *   import re, phonenumbers as pn
 *   from phonenumbers.phonemetadata import PhoneMetadata
 *   for r in sorted(pn.SUPPORTED_REGIONS):
 *       m = PhoneMetadata.metadata_for_region(r)
 *       ex = pn.example_number_for_type(r, pn.PhoneNumberType.MOBILE) or pn.example_number(r)
 *       if ex is None or m is None: continue
 *       national = pn.format_number(ex, pn.PhoneNumberFormat.NATIONAL)
 *       digits, trunk = re.sub(r'\D', '', national), m.national_prefix or ''
 *       lengths = set(m.general_desc.possible_length or [])
 *       lengths.add(len(digits) - len(trunk) if digits.startswith(trunk) else len(digits))
 *       print(r, national, sorted(lengths), trunk)
 *   "
 */
